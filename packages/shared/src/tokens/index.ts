import { createHash, randomBytes, timingSafeEqual } from 'node:crypto';

/**
 * Secrets exchanged by Nuera Dev (`@nuera/shared/tokens`). Server-only by convention (node:crypto):
 * never import it from a client component.
 *
 *   const token = generateRunnerToken();   // 'nrt_…', shown once to the administrator
 *   const tokenHash = hashToken(token);     // environments.token_hash / invitations.token_hash
 *   tokenFingerprint(token);                // '3f9a1c2e' — safe to display and log
 *   safeEqual(presented, expected);         // constant-time comparison
 *
 * Tokens themselves are never stored in clear nor logged: only their sha256 (and, for a runner
 * token, an AES-256-GCM ciphertext held by the web).
 */

/** Prefix of runner tokens generated by Nuera Dev (the former RUNNER_TOKEN without prefix stays accepted). */
export const RUNNER_TOKEN_PREFIX = 'nrt_';

/** base64url of 32 random bytes. */
const LINK_TOKEN_PATTERN = /^[A-Za-z0-9_-]{43}$/;

/** Runner token: `nrt_` + base64url(32 random bytes). */
export function generateRunnerToken(): string {
  return `${RUNNER_TOKEN_PREFIX}${randomBytes(32).toString('base64url')}`;
}

/** Invitation or recovery link token: base64url(32 random bytes), 43 characters. */
export function generateLinkToken(): string {
  return randomBytes(32).toString('base64url');
}

/** sha256 hex (64 characters) — what the database stores instead of a token. */
export function hashToken(token: string): string {
  return createHash('sha256').update(token, 'utf8').digest('hex');
}

/** First 8 hex characters of the hash: identifies a token in the UI and the logs without revealing it. */
export function tokenFingerprint(token: string): string {
  return hashToken(token).slice(0, 8);
}

/** true for a value shaped like a link token (validate a `/invitation/<jeton>` parameter before hashing it). */
export function isLinkToken(value: string): boolean {
  return LINK_TOKEN_PATTERN.test(value);
}

/** true for a runner token generated by Nuera Dev (`nrt_` format). */
export function isRunnerTokenFormat(value: string): boolean {
  return value.startsWith(RUNNER_TOKEN_PREFIX) && LINK_TOKEN_PATTERN.test(value.slice(RUNNER_TOKEN_PREFIX.length));
}

/**
 * Constant-time string comparison. Both values are hashed first, so neither their content nor their
 * length leaks through timing.
 */
export function safeEqual(a: string, b: string): boolean {
  const left = createHash('sha256').update(a, 'utf8').digest();
  const right = createHash('sha256').update(b, 'utf8').digest();
  return timingSafeEqual(left, right);
}
