export const REPORTER = l(
  "// Rapporteur node:test au format de Vitest : Nuera Dev lit les résultats en direct.",
  "import path from 'node:path';",
  '',
  'export default async function* rapport(source) {',
  '  const debut = Date.now();',
  '  const suites = new Map();',
  '  const echecs = [];',
  '  let reussis = 0;',
  '  let rates = 0;',
  '  let ignores = 0;',
  '  for await (const event of source) {',
  '    const data = event.data ?? {};',
  "    const fichier = data.file ? path.relative(process.cwd(), data.file).split(path.sep).join('/') : '';",
  "    if (event.type === 'test:start') {",
  '      const pile = suites.get(fichier) ?? [];',
  '      pile[data.nesting] = data.name;',
  '      pile.length = data.nesting + 1;',
  '      suites.set(fichier, pile);',
  '      continue;',
  '    }',
  "    if (event.type !== 'test:pass' && event.type !== 'test:fail') continue;",
  "    if (data.details?.type === 'suite') continue;",
  '    const parents = (suites.get(fichier) ?? []).slice(0, data.nesting);',
  "    const nom = [fichier, ...parents, data.name].filter(Boolean).join(' > ');",
  '    const ms = Math.max(1, Math.round(data.details?.duration_ms ?? 0));',
  '    if (data.skip || data.todo) {',
  '      ignores += 1;',
  '      yield ` ↓ ${nom}\\n`;',
  "    } else if (event.type === 'test:pass') {",
  '      reussis += 1;',
  '      yield ` ✓ ${nom} ${ms}ms\\n`;',
  '    } else {',
  '      rates += 1;',
  '      echecs.push({ nom, erreur: data.details?.error, fichier, ligne: data.line, colonne: data.column });',
  '      yield ` × ${nom} ${ms}ms\\n`;',
  '    }',
  '  }',
  '  for (const echec of echecs) {',
  '    const cause = echec.erreur?.cause ?? echec.erreur;',
  "    const message = String(cause?.message ?? cause ?? 'Échec').split('\\n');",
  '    yield `\\n FAIL  ${echec.nom}\\n`;',
  "    yield `${cause?.name ?? 'Error'}: ${message[0]}\\n`;",
  '    for (const ligne of message.slice(1, 7)) if (ligne.trim()) yield `${ligne}\\n`;',
  '    if (echec.fichier) yield ` ❯ ${echec.fichier}:${echec.ligne ?? 1}:${echec.colonne ?? 1}\\n`;',
  '  }',
  "  const parts = [rates ? `${rates} failed` : null, reussis ? `${reussis} passed` : null, ignores ? `${ignores} skipped` : null].filter(Boolean);",
  "  yield `\\n      Tests  ${parts.join(' | ') || 'aucun'} (${reussis + rates + ignores})\\n`;",
  '  yield `   Duration  ${((Date.now() - debut) / 1000).toFixed(2)}s\\n`;',
  '}',
);

