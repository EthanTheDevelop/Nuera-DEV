function devServer(title: string): string {
  return l(
    "import { createServer } from 'node:http';",
    '',
    'const port = Number(process.env.PORT ?? 0);',
    'const serveur = createServer((requete, reponse) => {',
    "  reponse.writeHead(200, { 'content-type': 'text/html; charset=utf-8' });",
    `  reponse.end('<!doctype html><title>${title}</title><h1>${title}</h1><p>Serveur de développement.</p>');`,
    '});',
    "serveur.listen(port, '127.0.0.1', () => {",
    '  const { port: reel } = serveur.address();',
    `  console.log(\`${title} · serveur de développement prêt sur http://localhost:\${reel}\`);`,
    '});',
  );
}

function buildScript(bundle: string): string {
  return l(
    "import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';",
    "import path from 'node:path';",
    '',
    'const debut = Date.now();',
    "const sources = readdirSync('src').filter((nom) => nom.endsWith('.js')).sort();",
    "const contenu = sources.map((nom) => `// ${nom}\\n${readFileSync(path.join('src', nom), 'utf8')}`).join('\\n');",
    "mkdirSync('dist', { recursive: true });",
    `writeFileSync(path.join('dist', '${bundle}'), contenu);`,
    `console.log(\`dist/${bundle} · \${sources.length} modules · \${(contenu.length / 1024).toFixed(1).replace('.', ',')} ko en \${Date.now() - debut} ms\`);`,
  );
}

