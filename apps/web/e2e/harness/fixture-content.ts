function packageJson(name: string, version: string, description: string, scripts: Record<string, string>, extra: Record<string, unknown> = {}): string {
  return `${JSON.stringify({ name, version, description, private: true, type: 'module', ...extra, scripts, engines: { node: '>=22' } }, null, 2)}\n`;
}

function packageLock(name: string, version: string): string {
  return `${JSON.stringify({ name, version, lockfileVersion: 3, requires: true, packages: { '': { name, version } } }, null, 2)}\n`;
}

